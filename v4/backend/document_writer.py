"""Create bounded, passive Office documents from plain text only.

No arbitrary archives, XML, executable formulas, macros, external relationships or
filesystem operations are accepted. Saving remains the Workspace approval job.
"""
import io
from pathlib import Path
import re
import zipfile
from xml.sax.saxutils import escape

MAX_CONTENT = 256 * 1024
FORMATS = frozenset({'.odt', '.docx', '.ods', '.xlsx', '.odp', '.pptx'})
ODF_MIME = {'.odt': 'application/vnd.oasis.opendocument.text',
            '.ods': 'application/vnd.oasis.opendocument.spreadsheet',
            '.odp': 'application/vnd.oasis.opendocument.presentation'}
XML = '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
ODF_NS = ('xmlns:office="urn:oasis:names:tc:opendocument:xmlns:office:1.0" '
          'xmlns:text="urn:oasis:names:tc:opendocument:xmlns:text:1.0" '
          'xmlns:table="urn:oasis:names:tc:opendocument:xmlns:table:1.0" '
          'xmlns:draw="urn:oasis:names:tc:opendocument:xmlns:drawing:1.0" '
          'xmlns:presentation="urn:oasis:names:tc:opendocument:xmlns:presentation:1.0" '
          'xmlns:svg="urn:oasis:names:tc:opendocument:xmlns:svg-compatible:1.0" '
          'xmlns:style="urn:oasis:names:tc:opendocument:xmlns:style:1.0" '
          'xmlns:fo="urn:oasis:names:tc:opendocument:xmlns:xsl-fo-compatible:1.0"')
REL = 'http://schemas.openxmlformats.org/officeDocument/2006/relationships/'
P_NS = ('xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main" '
        'xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main" '
        'xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"')
FORMAT_ERROR = 'Choose ODT, DOCX, ODS, XLSX, ODP or PPTX for a new document. Existing DOC and XLS files are read-only.'
CONTENT_ERROR = 'New document content must be plain text of at most 256 KiB.'
CONTROL_ERROR = 'Document content contains unsupported control characters.'
EXISTS_ERROR = 'Existing Office documents are read-only. Use a new filename for create_document.'
ROWS_ERROR = 'New spreadsheets support at most 1000 rows, 100 columns and 32767 characters per cell.'
SLIDES_ERROR = 'New presentations support at most 100 slides separated by blank lines.'
BUDGET_ERROR = 'The new document would exceed the 256 KiB readable-text limit. Use fewer rows, columns or slides.'


def _parts(path, content):
    extension = Path(path).suffix.lower()
    if extension not in FORMATS:
        raise ValueError(FORMAT_ERROR)
    if not isinstance(content, str):
        raise ValueError(CONTENT_ERROR)
    try:
        size = len(content.encode('utf-8'))
    except UnicodeError:
        raise ValueError(CONTENT_ERROR) from None
    if size > MAX_CONTENT:
        raise ValueError(CONTENT_ERROR)
    if any(not (c in '\t\n\r' or 0x20 <= ord(c) <= 0xD7FF or 0xE000 <= ord(c) <= 0xFFFD or 0x10000 <= ord(c) <= 0x10FFFF) for c in content):
        raise ValueError(CONTROL_ERROR)
    # One normalization is used for both generated bytes and readable preview.
    return extension, content.replace('\r\n', '\n').replace('\r', '\n')


def _zip(parts, mime=None):
    output = io.BytesIO()
    with zipfile.ZipFile(output, 'w') as archive:
        rows = ([('mimetype', mime)] if mime else []) + list(parts.items())
        for name, content in rows:
            info = zipfile.ZipInfo(name, date_time=(2020, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_STORED if name == 'mimetype' else zipfile.ZIP_DEFLATED
            info.external_attr = 0o600 << 16
            archive.writestr(info, content.encode('utf-8'))
    return output.getvalue()


def _odf_text(value):
    # ODF collapses literal whitespace. text:s/tab retain the supplied text.
    chunks = re.split(r'( +|\t)', value)
    return ''.join('<text:s text:c="'+str(len(x))+'"/>' if x.startswith(' ') else '<text:tab/>' if x == '\t' else escape(x) for x in chunks)


def _paragraphs(content, kind='odf'):
    if kind == 'docx':
        return ''.join('<w:p><w:r><w:t xml:space="preserve">'+escape(line)+'</w:t></w:r></w:p>' for line in content.split('\n'))
    if kind == 'pptx':
        return ''.join('<a:p><a:r><a:rPr lang="en-US" sz="2000"/><a:t>'+escape(line)+'</a:t></a:r><a:endParaRPr lang="en-US"/></a:p>' for line in content.split('\n'))
    return ''.join('<text:p>'+_odf_text(line)+'</text:p>' for line in content.split('\n'))


def _rows(content):
    rows = [line.split('\t') for line in content.split('\n')]
    if len(rows) > 1000 or any(len(row) > 100 or any(len(cell) > 32767 for cell in row) for row in rows):
        raise ValueError(ROWS_ERROR)
    return rows


def _slides(content):
    slides = re.split(r'\n[ \t]*\n', content)
    if len(slides) > 100:
        raise ValueError(SLIDES_ERROR)
    return slides


def _odf(extension, content):
    styles = '<office:styles><style:default-style style:family="paragraph"><style:text-properties fo:font-size="14pt"/></style:default-style></office:styles>'
    automatic = ''
    if extension == '.odt':
        body = '<office:text>'+_paragraphs(content)+'</office:text>'
    elif extension == '.ods':
        rows = _rows(content)
        automatic = '<office:automatic-styles><style:style style:name="column" style:family="table-column"><style:table-column-properties style:column-width="6cm"/></style:style><style:style style:name="cell" style:family="table-cell"><style:table-cell-properties fo:wrap-option="wrap"/></style:style></office:automatic-styles>'
        table = ''.join('<table:table-row>'+''.join('<table:table-cell table:style-name="cell" office:value-type="string"><text:p>'+_odf_text(cell)+'</text:p></table:table-cell>' for cell in row)+'</table:table-row>' for row in rows)
        body = '<office:spreadsheet><table:table table:name="Sheet1"><table:table-column table:style-name="column" table:number-columns-repeated="'+str(max(map(len,rows)))+'"/>'+table+'</table:table></office:spreadsheet>'
    else:
        body = '<office:presentation>'+''.join('<draw:page draw:name="Slide'+str(n)+'" draw:master-page-name="Default"><draw:frame svg:x="1.4cm" svg:y="1.2cm" svg:width="25.2cm" svg:height="13.3cm"><draw:text-box>'+_paragraphs(slide)+'</draw:text-box></draw:frame></draw:page>' for n, slide in enumerate(_slides(content), 1))+'</office:presentation>'
        styles += '<office:automatic-styles><style:page-layout style:name="pm1"><style:page-layout-properties fo:page-width="28cm" fo:page-height="15.75cm" style:print-orientation="landscape"/></style:page-layout></office:automatic-styles><office:master-styles><style:master-page style:name="Default" style:page-layout-name="pm1"/></office:master-styles>'
    parts = {'content.xml': XML+'<office:document-content '+ODF_NS+' office:version="1.3">'+automatic+'<office:body>'+body+'</office:body></office:document-content>',
             'styles.xml': XML+'<office:document-styles '+ODF_NS+' office:version="1.3">'+styles+'</office:document-styles>'}
    parts['META-INF/manifest.xml'] = XML+'<manifest:manifest xmlns:manifest="urn:oasis:names:tc:opendocument:xmlns:manifest:1.0" manifest:version="1.3"><manifest:file-entry manifest:full-path="/" manifest:media-type="'+ODF_MIME[extension]+'" manifest:version="1.3"/>'+''.join('<manifest:file-entry manifest:full-path="'+name+'" manifest:media-type="text/xml"/>' for name in parts)+'</manifest:manifest>'
    return _zip(parts, ODF_MIME[extension])


def _rels(rows):
    return XML+'<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'+''.join('<Relationship Id="'+name+'" Type="'+REL+kind+'" Target="'+target+'"/>' for name, kind, target in rows)+'</Relationships>'


def _ooxml(parts, main, types):
    parts = {**parts, '_rels/.rels': _rels([('rId1', 'officeDocument', main)])}
    parts['[Content_Types].xml'] = XML+'<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/>'+''.join('<Override PartName="/'+name+'" ContentType="application/vnd.openxmlformats-officedocument.'+kind+'+xml"/>' for name, kind in types)+'</Types>'
    return _zip(parts)


def _docx(content):
    document = XML+'<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body>'+_paragraphs(content, 'docx')+'<w:sectPr><w:pgSz w:w="11906" w:h="16838"/><w:pgMar w:top="1134" w:right="1134" w:bottom="1134" w:left="1134"/></w:sectPr></w:body></w:document>'
    return _ooxml({'word/document.xml': document}, 'word/document.xml', [('word/document.xml', 'wordprocessingml.document.main')])


def _column(number):
    name = ''
    while number:
        number, remainder = divmod(number-1, 26)
        name = chr(65+remainder)+name
    return name


def _xlsx(content):
    values = _rows(content)
    rows = ''.join('<row r="'+str(n)+'">'+''.join('<c r="'+_column(k)+str(n)+'" t="inlineStr"><is><t xml:space="preserve">'+escape(cell)+'</t></is></c>' for k, cell in enumerate(row, 1))+'</row>' for n, row in enumerate(values, 1))
    parts = {'xl/workbook.xml': XML+'<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"><sheets><sheet name="Sheet1" sheetId="1" r:id="rId1"/></sheets></workbook>',
             'xl/_rels/workbook.xml.rels': _rels([('rId1', 'worksheet', 'worksheets/sheet1.xml')]),
             'xl/worksheets/sheet1.xml': XML+'<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><cols><col min="1" max="'+str(max(map(len,values)))+'" width="28" customWidth="1"/></cols><sheetData>'+rows+'</sheetData></worksheet>'}
    return _ooxml(parts, 'xl/workbook.xml', [('xl/workbook.xml', 'spreadsheetml.sheet.main'), ('xl/worksheets/sheet1.xml', 'spreadsheetml.worksheet')])


def _shape_tree(text=''):
    return '<p:spTree><p:nvGrpSpPr><p:cNvPr id="1" name=""/><p:cNvGrpSpPr/><p:nvPr/></p:nvGrpSpPr><p:grpSpPr><a:xfrm><a:off x="0" y="0"/><a:ext cx="0" cy="0"/><a:chOff x="0" y="0"/><a:chExt cx="0" cy="0"/></a:xfrm></p:grpSpPr>'+text+'</p:spTree>'


def _theme():
    colors = [('dk1','000000'),('lt1','FFFFFF'),('dk2','303030'),('lt2','F4F4F4'),('accent1','FF6633'),('accent2','376F91'),('accent3','4F9153'),('accent4','A161BD'),('accent5','D8AC37'),('accent6','24999E'),('hlink','0000EE'),('folHlink','551A8B')]
    fill = '<a:solidFill><a:schemeClr val="phClr"/></a:solidFill>'
    line = '<a:ln w="9525">'+fill+'<a:prstDash val="solid"/><a:miter lim="800000"/></a:ln>'
    fonts = ''.join('<a:'+kind+'><a:latin typeface="Arial"/><a:ea typeface=""/><a:cs typeface=""/></a:'+kind+'>' for kind in ['majorFont','minorFont'])
    return XML+'<a:theme xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main" name="VibeZ"><a:themeElements><a:clrScheme name="VibeZ">'+''.join('<a:'+name+'><a:srgbClr val="'+color+'"/></a:'+name+'>' for name, color in colors)+'</a:clrScheme><a:fontScheme name="VibeZ">'+fonts+'</a:fontScheme><a:fmtScheme name="VibeZ"><a:fillStyleLst>'+fill*3+'</a:fillStyleLst><a:lnStyleLst>'+line*3+'</a:lnStyleLst><a:effectStyleLst>'+('<a:effectStyle><a:effectLst/></a:effectStyle>'*3)+'</a:effectStyleLst><a:bgFillStyleLst>'+fill*3+'</a:bgFillStyleLst></a:fmtScheme></a:themeElements></a:theme>'


def _pptx(content):
    slides = _slides(content)
    colormap = '<p:clrMap accent1="accent1" accent2="accent2" accent3="accent3" accent4="accent4" accent5="accent5" accent6="accent6" bg1="lt1" bg2="lt2" folHlink="folHlink" hlink="hlink" tx1="dk1" tx2="dk2"/>'
    parts = {'ppt/presentation.xml': XML+'<p:presentation '+P_NS+'><p:sldMasterIdLst><p:sldMasterId id="2147483648" r:id="rId1"/></p:sldMasterIdLst><p:sldIdLst>'+''.join('<p:sldId id="'+str(255+n)+'" r:id="rId'+str(n+2)+'"/>' for n in range(1,len(slides)+1))+'</p:sldIdLst><p:sldSz cx="10080000" cy="5670000" type="screen16x9"/><p:notesSz cx="6858000" cy="9144000"/></p:presentation>',
             'ppt/_rels/presentation.xml.rels': _rels([('rId1','slideMaster','slideMasters/slideMaster1.xml'),('rId2','presProps','presProps.xml')]+[('rId'+str(n+2),'slide','slides/slide'+str(n)+'.xml') for n in range(1,len(slides)+1)]),
             'ppt/presProps.xml': XML+'<p:presentationPr '+P_NS+'/>',
             'ppt/slideMasters/slideMaster1.xml': XML+'<p:sldMaster '+P_NS+'><p:cSld>'+_shape_tree()+'</p:cSld>'+colormap+'<p:sldLayoutIdLst><p:sldLayoutId id="2147483649" r:id="rId1"/></p:sldLayoutIdLst><p:txStyles><p:titleStyle/><p:bodyStyle/><p:otherStyle/></p:txStyles></p:sldMaster>',
             'ppt/slideMasters/_rels/slideMaster1.xml.rels': _rels([('rId1','slideLayout','../slideLayouts/slideLayout1.xml'),('rId2','theme','../theme/theme1.xml')]),
             'ppt/slideLayouts/slideLayout1.xml': XML+'<p:sldLayout '+P_NS+' type="blank" preserve="1"><p:cSld name="Blank">'+_shape_tree()+'</p:cSld><p:clrMapOvr><a:masterClrMapping/></p:clrMapOvr></p:sldLayout>',
             'ppt/slideLayouts/_rels/slideLayout1.xml.rels': _rels([('rId1','slideMaster','../slideMasters/slideMaster1.xml')]),
             'ppt/theme/theme1.xml': _theme()}
    types = [('ppt/presentation.xml','presentationml.presentation.main'),('ppt/presProps.xml','presentationml.presProps'),('ppt/slideMasters/slideMaster1.xml','presentationml.slideMaster'),('ppt/slideLayouts/slideLayout1.xml','presentationml.slideLayout'),('ppt/theme/theme1.xml','theme')]
    for n, slide in enumerate(slides, 1):
        shape = '<p:sp><p:nvSpPr><p:cNvPr id="2" name="Text"/><p:cNvSpPr txBox="1"/><p:nvPr/></p:nvSpPr><p:spPr><a:xfrm><a:off x="504000" y="432000"/><a:ext cx="9072000" cy="4788000"/></a:xfrm><a:prstGeom prst="rect"><a:avLst/></a:prstGeom><a:noFill/><a:ln><a:noFill/></a:ln></p:spPr><p:txBody><a:bodyPr wrap="square"/><a:lstStyle/>'+_paragraphs(slide,'pptx')+'</p:txBody></p:sp>'
        name='ppt/slides/slide'+str(n)+'.xml'
        parts[name]=XML+'<p:sld '+P_NS+'><p:cSld>'+_shape_tree(shape)+'</p:cSld><p:clrMapOvr><a:masterClrMapping/></p:clrMapOvr></p:sld>'
        parts['ppt/slides/_rels/slide'+str(n)+'.xml.rels']=_rels([('rId1','slideLayout','../slideLayouts/slideLayout1.xml')])
        types.append((name,'presentationml.slide'))
    return _ooxml(parts,'ppt/presentation.xml',types)


def render(path, content):
    """Return normalized preview, file extension and deterministic document bytes."""
    extension, text = _parts(path, content)
    raw = _odf(extension,text) if extension in ODF_MIME else {'.docx':_docx,'.xlsx':_xlsx,'.pptx':_pptx}[extension](text)
    return text, extension, raw
